package com.v1f.app.patch;

import android.accessibilityservice.AccessibilityService;
import android.content.Intent;
import android.os.Handler;
import android.os.Looper;
import android.os.SystemClock;
import android.provider.Settings;
import android.view.accessibility.AccessibilityEvent;
import android.widget.Toast;
import com.v1f.app.protection.overlay.MeteorShieldOverlay;

/**
 * Two separate paths:
 * - Blocked label: three BACKs, one Settings launch, 500ms, three BACKs.
 * - User leaves Settings: show shield, 250ms, launch twice 250ms apart,
 *   wait 1000ms, three BACKs spaced by 300ms, then hide.
 */
public final class SettingsBackCoordinator {
    private static final Handler MAIN = new Handler(Looper.getMainLooper());
    private static final String SETTINGS = "com.android.settings";
    private static AccessibilityService service;
    private static MeteorShieldOverlay shield;
    private static Runnable pending;
    private static Runnable deadlineTask;
    private static long deadlineAt;
    private static final long MAX_DURATION_MS = 7500L;
    private static int generation;
    private static final int IDLE = 0;
    private static final int WAIT_SINGLE_LAUNCH = 1;
    private static final int FINAL_BACKS = 2;
    private static final int INITIAL_BACKS = 3;
    private static final int EXIT_WAIT_FIRST_LAUNCH = 4;
    private static final int EXIT_WAIT_SECOND_LAUNCH = 5;
    private static final int EXIT_WAIT_FINAL_BACKS = 6;
    private static int stage;
    private static long quietUntil;

    private SettingsBackCoordinator() {}

    public static void initialize(AccessibilityService current) {
        // Keep window delivery configuration, but retire the old return BACK pair.
        SettingsReturnEngine.initialize(current);
        SettingsReturnEngine.cancel();
        if (SettingsSessionGate.isActive()) SettingsExitMonitor.initialize(current);
    }

    public static boolean isNavigating() {
        return SettingsSessionGate.isActive() && (stage != 0 || SystemClock.elapsedRealtime() < quietUntil);
    }

    public static void trigger(final AccessibilityService current,
                               final MeteorShieldOverlay overlay) {
        if (SettingsSessionGate.isActive()) start(current, overlay, true, MAX_DURATION_MS);
    }

    public static void triggerSettingsExit(final AccessibilityService current) {
        if (current == null || !SettingsSessionGate.isActive() || isNavigating()) return;
        start(current, new MeteorShieldOverlay(current), false, 5000L);
    }

    private static void start(final AccessibilityService current,
                              final MeteorShieldOverlay overlay,
                              final boolean initialBacks, final long durationMs) {
        if (current == null || !SettingsSessionGate.isActive()) return;
        if (Looper.myLooper() != Looper.getMainLooper()) {
            MAIN.post(() -> start(current, overlay, initialBacks, durationMs));
            return;
        }
        if (!SettingsSessionGate.isActive() || stage != 0 || SystemClock.elapsedRealtime() < quietUntil) return;
        SettingsReturnEngine.cancel();
        service = current;
        shield = overlay;
        generation++;
        // Suppress all Settings departures generated by this transaction,
        // including a delayed event for the last global BACK.
        SettingsExitMonitor.markOwnNavigation();
        stage = initialBacks ? INITIAL_BACKS : EXIT_WAIT_FIRST_LAUNCH;
        deadlineAt = SystemClock.elapsedRealtime() + durationMs;
        try {
            if (shield == null || !shield.show()) {
                fail("Could not show protection shield");
                return;
            }
        } catch (RuntimeException error) {
            fail("Could not show protection shield");
            return;
        }
        // Independent watchdog: never reset by launch or BACK retries.
        final int token = generation;
        deadlineTask = () -> {
            if (token == generation && stage != 0) finish();
        };
        MAIN.postDelayed(deadlineTask, durationMs);
        // The exit path intentionally starts exactly 250ms after showing the shield.
        // Keep the existing blocked-label path timing unchanged.
        if (initialBacks) schedule(() -> sendBack(1), 32L);
        else schedule(SettingsBackCoordinator::launchExitSettingsFirst, 250L);
    }

    private static boolean launchSettings() {
        if (expired() || service == null) return false;
        try {
            Intent intent = service.getPackageManager().getLaunchIntentForPackage(SETTINGS);
            if (intent == null) intent = new Intent(Settings.ACTION_SETTINGS).setPackage(SETTINGS);
            intent.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK);
            service.startActivity(intent);
            return true;
        } catch (RuntimeException error) {
            fail("Could not open Settings");
            return false;
        }
    }

    private static void openSettings() {
        if (expired()) return;
        stage = WAIT_SINGLE_LAUNCH;
        if (launchSettings()) {
            // Original blocked-label behavior is unchanged.
            schedule(SettingsBackCoordinator::beginBacks, 500L);
        }
    }

    private static void launchExitSettingsFirst() {
        if (expired() || stage != EXIT_WAIT_FIRST_LAUNCH) return;
        if (launchSettings()) {
            stage = EXIT_WAIT_SECOND_LAUNCH;
            schedule(SettingsBackCoordinator::launchExitSettingsSecond, 250L);
        }
    }

    private static void launchExitSettingsSecond() {
        if (expired() || stage != EXIT_WAIT_SECOND_LAUNCH) return;
        if (launchSettings()) {
            stage = EXIT_WAIT_FINAL_BACKS;
            schedule(SettingsBackCoordinator::beginBacks, 1000L);
        }
    }

    private static boolean expired() {
        if (stage == IDLE) return true;
        if (!SettingsSessionGate.isActive()) { cancel(); return true; }
        if (SystemClock.elapsedRealtime() < deadlineAt) return false;
        finish();
        return true;
    }

    public static boolean observe(AccessibilityService current, AccessibilityEvent event) {
        if (!SettingsSessionGate.isActive()) {
            if (stage != 0 || shield != null) cancel();
            else SettingsExitMonitor.detach();
            return false;
        }
        SettingsExitMonitor.observe(current, event);
        if (stage == IDLE) return SystemClock.elapsedRealtime() < quietUntil;
        if (expired()) return true;
        // Consume navigation events without using them to start the final BACKs.
        return true;
    }

    private static void beginBacks() {
        if (expired() || (stage != WAIT_SINGLE_LAUNCH && stage != EXIT_WAIT_FINAL_BACKS)) return;
        stage = FINAL_BACKS;
        removePending();
        sendBack(1);
    }

    private static void sendBack(final int number) {
        if (expired() || (stage != FINAL_BACKS && stage != INITIAL_BACKS) || service == null) return;
        boolean accepted = false;
        try { accepted = service.performGlobalAction(AccessibilityService.GLOBAL_ACTION_BACK); }
        catch (RuntimeException ignored) {}
        if (!accepted) {
            schedule(() -> sendBack(number), 150L);
        } else if (number < 3) {
            schedule(() -> sendBack(number + 1), 300L);
        } else if (stage == INITIAL_BACKS) {
            // Let the third global BACK settle before bringing Settings forward.
            schedule(SettingsBackCoordinator::openSettings, 300L);
        } else {
            finish();
        }
    }

    private static void schedule(Runnable action, long delay) {
        removePending();
        final int token = generation;
        pending = () -> {
            if (token != generation || expired()) return;
            pending = null;
            action.run();
        };
        MAIN.postDelayed(pending, delay);
    }

    private static void removePending() {
        if (pending != null) MAIN.removeCallbacks(pending);
        pending = null;
    }

    private static void finish() {
        generation++;
        removePending();
        if (deadlineTask != null) MAIN.removeCallbacks(deadlineTask);
        deadlineTask = null;
        deadlineAt = 0L;
        stage = IDLE;
        quietUntil = SystemClock.elapsedRealtime() + 700L;
        if (shield != null) {
            try { shield.hide(); } catch (RuntimeException ignored) {}
        }
        shield = null;
        service = null;
    }

    private static void fail(String message) {
        if (service != null) Toast.makeText(service, message, Toast.LENGTH_SHORT).show();
        finish();
    }

    public static void detach() { cancel(); }

    public static void cancel() {
        if (Looper.myLooper() != Looper.getMainLooper()) {
            MAIN.post(SettingsBackCoordinator::cancel);
            return;
        }
        SettingsReturnEngine.cancel();
        SettingsExitMonitor.detach();
        finish();
    }
}
